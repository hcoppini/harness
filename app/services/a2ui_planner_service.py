def process_plan_message(
    user_message: str,
    stance: str = "coach",
    date_str: Optional[str] = None,
    conn: Optional[sqlite3.Connection] = None,
) -> Dict[str, Any]:
    """
    Processes a Plans/Logs chatbox message:
      - Attempts local Ollama -> free cloud fallback -> deterministic offline parser
      - Logs conversation cleanly in diary_conversations
      - Emits an A2UI `agent_to_renderer` envelope whenever an outing/plan change is detected
    """
    close_conn = False
    if conn is None:
        conn = get_connection()
        close_conn = True

    diary_service.ensure_diary_tables(conn)
    target_date = date_str or datetime.now().strftime("%Y-%m-%d")
    ref_dt = datetime.strptime(target_date[:10], "%Y-%m-%d").date()
    clean_msg = (user_message or "").strip()

    existing_outings = get_outings()
    sys_prompt = _build_llm_system_prompt(target_date, existing_outings)

    llm_parsed: Optional[Dict[str, Any]] = None
    provider = "local_parser"

    ollama_res = _call_ollama_json(sys_prompt, clean_msg)
    if ollama_res:
        llm_parsed, provider = ollama_res
    else:
        cloud_res = _call_free_cloud_json(sys_prompt, clean_msg)
        if cloud_res:
            llm_parsed, provider = cloud_res

    outing_data: Optional[Dict[str, Any]] = None
    reply_text: str = ""

    if llm_parsed and llm_parsed.get("intent") == "plan_outing" and isinstance(llm_parsed.get("outing"), dict):
        cand = llm_parsed["outing"]
        sd = str(cand.get("start_date") or "")[:10]
        ed = str(cand.get("end_date") or sd)[:10]
        if re.match(r"^\d{4}-\d{2}-\d{2}$", sd) and re.match(r"^\d{4}-\d{2}-\d{2}$", ed):
            mode_val = "break" if str(cand.get("mode", "")).lower() == "break" else "travel"
            outing_data = {
                "name": str(cand.get("name") or "Planned Outing").strip(),
                "destination": str(cand.get("destination") or "Travel").strip(),
                "start_date": sd,
                "end_date": ed,
                "mode": mode_val,
                "description": str(cand.get("description") or "").strip()
                or ("Break Sprint: programming & Sidequests." if mode_val == "break" else "Confirmed outing: 30-45m floor."),
            }
            reply_text = str(llm_parsed.get("reply") or "").strip()

    # Fallback deterministic outing parser if LLM was unavailable or missed explicit dates
    if outing_data is None:
        offline_outing = _parse_outing_offline(clean_msg, ref_dt)
        if offline_outing:
            outing_data = offline_outing
            provider = "local_parser"
            reply_text = (
                f"Parsed {outing_data['name']} ({outing_data['start_date']} → {outing_data['end_date']}). "
                f"Review the rearranged plan on the right and hit Apply to update Harness."
            )

    envelope: Optional[Dict[str, Any]] = None
    if outing_data:
        affected_exams, schedule_diff = _compute_conflicts_and_diff(
            outing_data["start_date"],
            outing_data["end_date"],
            outing_data["mode"],
            outing_data["destination"],
            conn,
        )
        if not reply_text:
            reply_text = f"Prepared A2UI plan rearrangement for {outing_data['name']}. Click Apply to save."
        envelope = build_outing_a2ui_envelope(
            outing=outing_data,
            affected_exams=affected_exams,
            schedule_diff=schedule_diff,
            provider=provider,
            reply=reply_text,
        )

    # Persist message pair into diary_conversations
    conv = diary_service.get_diary_conversation(target_date, conn=conn)
    messages = list(conv.get("messages") or [])
    now_hm = datetime.now().strftime("%H:%M")
    messages.append({"role": "user", "content": clean_msg, "timestamp": now_hm})

    if not reply_text:
        if llm_parsed and llm_parsed.get("reply"):
            reply_text = str(llm_parsed["reply"]).strip()
        else:
            reply_text = diary_service._generate_ai_reply(messages, stance=stance)

    assistant_entry: Dict[str, Any] = {
        "role": "assistant",
        "stance": stance,
        "provider": provider,
        "content": reply_text,
        "timestamp": datetime.now().strftime("%H:%M"),
    }
    if envelope:
        assistant_entry["surfaceId"] = envelope["surfaceId"]
    messages.append(assistant_entry)

    conn.execute(
        """
        UPDATE diary_conversations
        SET stance = ?, messages_json = ?, updated_at = CURRENT_TIMESTAMP
        WHERE id = ?
        """,
        (stance, json.dumps(messages), conv["id"]),
    )
    conn.commit()
    updated_conv = diary_service.get_diary_conversation(target_date, conn=conn)

    if close_conn:
        conn.close()

    result: Dict[str, Any] = {
        "conversation": updated_conv,
        "provider": provider,
        "reply": reply_text,
        "outings": get_outings(),
    }
    if envelope:
        result["agent_to_renderer"] = envelope
    return result


def apply_a2ui_action(
    action_name: str,
    payload: Dict[str, Any],
    conn: Optional[sqlite3.Connection] = None,
) -> Dict[str, Any]:
    """Executes a whitelisted A2UI `@call` action after explicit user confirmation."""
    close_conn = False
    if conn is None:
        conn = get_connection()
        close_conn = True

    try:
        if action_name == "recompute_preview":
            outing = (payload or {}).get("outing") or {}
            sd = str(outing.get("start_date") or "")[:10]
            ed = str(outing.get("end_date") or sd)[:10]
            mode = "break" if str(outing.get("mode", "")).lower() == "break" else "travel"
            dest = str(outing.get("destination") or "Outing").strip()
            affected_exams, schedule_diff = _compute_conflicts_and_diff(sd, ed, mode, dest, conn)
            return {
                "success": True,
                "affected_exams": affected_exams,
                "schedule_diff": schedule_diff,
            }

        if action_name == "apply_outing":
            outing = (payload or {}).get("outing") or payload or {}
            sd = str(outing.get("start_date") or "").strip()[:10]
            ed = str(outing.get("end_date") or sd).strip()[:10]
            if not re.match(r"^\d{4}-\d{2}-\d{2}$", sd) or not re.match(r"^\d{4}-\d{2}-\d{2}$", ed):
                return {"success": False, "error": "Invalid start_date or end_date (expected YYYY-MM-DD)."}
            if ed < sd:
                sd, ed = ed, sd

            mode = "break" if str(outing.get("mode", "")).lower() == "break" else "travel"
            name = str(outing.get("name") or f"Outing ({sd})").strip()
            destination = str(outing.get("destination") or ("Break Sprint" if mode == "break" else "Travel")).strip()
            description = str(outing.get("description") or "").strip() or (
                "Confirmed via A2UI Planner."
            )

            slug = re.sub(r"[^a-z0-9]+", "_", destination.lower()).strip("_") or "outing"
            win_id = str(outing.get("id") or f"a2ui_{slug}_{sd.replace('-', '')}")

            _seed_sqlite_windows_if_empty(conn)
            new_win = {
                "id": win_id,
                "name": name,
                "destination": destination,
                "type": mode,
                "confirmed": True,
                "start_date": sd,
                "end_date": ed,
                "description": description,
                "source": "a2ui",
            }
            conn.execute(
                """
                INSERT INTO travel_windows
                (id, name, destination, type, confirmed, start_date, end_date, description, source, updated_at)
                VALUES (?, ?, ?, ?, 1, ?, ?, ?, 'a2ui', CURRENT_TIMESTAMP)
                ON CONFLICT(id) DO UPDATE SET
                    name = excluded.name,
                    destination = excluded.destination,
                    type = excluded.type,
                    confirmed = excluded.confirmed,
                    start_date = excluded.start_date,
                    end_date = excluded.end_date,
                    description = excluded.description,
                    source = excluded.source,
                    updated_at = CURRENT_TIMESTAMP
                """,
                (win_id, name, destination, mode, sd, ed, description),
            )
            conn.commit()
            windows = get_outings(conn=conn)
            _save_windows_file({"windows": windows})
            return {
                "success": True,
                "action": "apply_outing",
                "outing": new_win,
                "outings": windows,
            }

        if action_name == "delete_outing":
            outing_id = str((payload or {}).get("outing_id") or (payload or {}).get("id") or "").strip()
            if not outing_id:
                return {"success": False, "error": "outing_id is required."}
            _seed_sqlite_windows_if_empty(conn)
            conn.execute("DELETE FROM travel_windows WHERE id = ?", (outing_id,))
            conn.commit()
            windows = get_outings(conn=conn)
            _save_windows_file({"windows": windows})
            return {
                "success": True,
                "action": "delete_outing",
                "deleted_id": outing_id,
                "outings": windows,
            }

        return {"success": False, "error": f"Unknown A2UI action: {action_name}"}
    finally:
        if close_conn:
            conn.close()
