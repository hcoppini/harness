def ensure_travel_window_tables(conn: sqlite3.Connection) -> None:
    """Ensures the SQLite travel_windows table exists for durable cross-device outing sync."""
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS travel_windows (
            id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            destination TEXT DEFAULT '',
            type TEXT NOT NULL DEFAULT 'travel',
            confirmed INTEGER NOT NULL DEFAULT 1,
            start_date TEXT NOT NULL,
            end_date TEXT NOT NULL,
            description TEXT DEFAULT '',
            source TEXT DEFAULT 'config',
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
        """
    )
    conn.commit()


def _seed_sqlite_windows_if_empty(conn: sqlite3.Connection) -> None:
    ensure_travel_window_tables(conn)
    cnt = conn.execute("SELECT COUNT(*) FROM travel_windows").fetchone()[0]
    if cnt > 0:
        return
    file_windows = _load_windows_file().get("windows", [])
    for w in file_windows:
        if not w.get("id") or not w.get("start_date") or not w.get("end_date"):
            continue
        conn.execute(
            """
            INSERT OR IGNORE INTO travel_windows
            (id, name, destination, type, confirmed, start_date, end_date, description, source)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                str(w["id"]),
                str(w.get("name") or "Outing"),
                str(w.get("destination") or ""),
                str(w.get("type") or "travel"),
                1 if w.get("confirmed", True) else 0,
                str(w["start_date"])[:10],
                str(w["end_date"])[:10],
                str(w.get("description") or ""),
                str(w.get("source") or "config"),
            ),
        )
    if file_windows:
        conn.commit()


def _load_windows_file() -> Dict[str, Any]:
    if TRAVEL_WINDOWS_FILE.exists():
        try:
            with open(TRAVEL_WINDOWS_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, dict) and isinstance(data.get("windows"), list):
                    return data
        except Exception:
            pass
    return {"windows": []}


def _save_windows_file(data: Dict[str, Any]) -> None:
    TRAVEL_WINDOWS_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(TRAVEL_WINDOWS_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def get_outings(conn: Optional[sqlite3.Connection] = None) -> List[Dict[str, Any]]:
    """Returns all outings/break windows from SQLite (seeded from travel_windows.json if empty)."""
    close_conn = False
    if conn is None:
        conn = get_connection()
        close_conn = True
    try:
        _seed_sqlite_windows_if_empty(conn)
        rows = conn.execute(
            """
            SELECT id, name, destination, type, confirmed, start_date, end_date, description, source
            FROM travel_windows
            ORDER BY start_date ASC, id ASC
            """
        ).fetchall()
        return [
            {
                "id": r["id"],
                "name": r["name"],
                "destination": r["destination"] or "",
                "type": r["type"] or "travel",
                "confirmed": bool(r["confirmed"]),
                "start_date": r["start_date"],
                "end_date": r["end_date"],
                "description": r["description"] or "",
                "source": r["source"] or "config",
            }
            for r in rows
        ]
    except Exception:
        return list(_load_windows_file().get("windows", []))
    finally:
        if close_conn:
            conn.close()


def _probe_ollama() -> Tuple[bool, List[str]]:
    """Quick 1.5s check for running local Ollama daemon and installed models."""
    try:
        req = urllib.request.Request(f"{OLLAMA_BASE_URL}/api/tags", method="GET")
        with urllib.request.urlopen(req, timeout=1.5) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
            models = [m.get("name", "") for m in payload.get("models", []) if m.get("name")]
            return True, models
    except Exception:
        return False, []


def get_a2ui_status() -> Dict[str, Any]:
    """Reports local Ollama & free cloud fallback readiness for Plans/Logs UI badge."""
    ollama_up, models = _probe_ollama()
    preferred_model = DEFAULT_OLLAMA_MODEL or (models[0] if models else "llama3:latest")
    has_gemini = bool(os.environ.get("GEMINI_API_KEY"))
    has_groq = bool(os.environ.get("GROQ_API_KEY"))

    if ollama_up and models:
        active = f"ollama:{preferred_model}"
        label = f"OLLAMA • {preferred_model}"
    elif has_gemini:
        active = "gemini:gemini-2.0-flash"
        label = "GEMINI FREE"
    elif has_groq:
        active = "groq:llama-3.3-70b"
        label = "GROQ FREE"
    else:
        active = "local_parser"
        label = "LOCAL PARSER"

    return {
        "ollama_running": ollama_up,
        "ollama_models": models,
        "preferred_model": preferred_model,
        "has_gemini_fallback": has_gemini,
        "has_groq_fallback": has_groq,
        "active_provider": active,
        "provider_label": label,
        "catalog_components": list(A2UI_CATALOG.keys()),
    }


def _call_ollama_json(
    system_prompt: str,
    user_prompt: str,
    model_name: Optional[str] = None,
) -> Optional[Tuple[Dict[str, Any], str]]:
    """Calls local Ollama /api/chat requesting strict JSON output."""
    ollama_up, models = _probe_ollama()
    if not ollama_up or not models:
        return None
    chosen = model_name or DEFAULT_OLLAMA_MODEL or models[0]
    body = {
        "model": chosen,
        "stream": False,
        "format": "json",
        "options": {"temperature": 0.2},
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    }
    try:
        req = urllib.request.Request(
            f"{OLLAMA_BASE_URL}/api/chat",
            data=json.dumps(body).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=25) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            raw_content = (data.get("message") or {}).get("content") or ""
            parsed = json.loads(raw_content)
            if isinstance(parsed, dict):
                return parsed, f"ollama:{chosen}"
    except Exception:
        return None
    return None


def _call_free_cloud_json(
    system_prompt: str,
    user_prompt: str,
) -> Optional[Tuple[Dict[str, Any], str]]:
    """Free-tier cloud fallback (Gemini 2.0 Flash or Groq) for Vercel / iPhone PWA."""
    gemini_key = os.environ.get("GEMINI_API_KEY")
    if gemini_key:
        url = (
            "https://generativelanguage.googleapis.com/v1beta/models/"
            f"gemini-2.0-flash:generateContent?key={gemini_key}"
        )
        payload = {
            "system_instruction": {"parts": [{"text": system_prompt}]},
            "contents": [{"role": "user", "parts": [{"text": user_prompt}]}],
            "generationConfig": {
                "temperature": 0.2,
                "responseMimeType": "application/json",
            },
        }
        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                text = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(text)
                if isinstance(parsed, dict):
                    return parsed, "gemini:gemini-2.0-flash"
        except Exception:
            pass

    groq_key = os.environ.get("GROQ_API_KEY")
    if groq_key:
        payload = {
            "model": "llama-3.3-70b-versatile",
            "temperature": 0.2,
            "response_format": {"type": "json_object"},
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
        }
        try:
            req = urllib.request.Request(
                "https://api.groq.com/openai/v1/chat/completions",
                data=json.dumps(payload).encode("utf-8"),
                headers={
                    "Content-Type": "application/json",
                    "Authorization": f"Bearer {groq_key}",
                },
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                text = data["choices"][0]["message"]["content"]
                parsed = json.loads(text)
                if isinstance(parsed, dict):
                    return parsed, "groq:llama-3.3-70b"
        except Exception:
            pass

    return None


def _resolve_year(month: int, day: int, ref_dt: date) -> int:
    """Resolves year for a month/day mention relative to reference date."""
    try:
        candidate = date(ref_dt.year, month, day)
    except ValueError:
        return ref_dt.year
    if candidate < ref_dt - timedelta(days=30):
        return ref_dt.year + 1
    return ref_dt.year


def _extract_destination(text: str) -> str:
    """Extracts a clean destination name from phrases like 'to Krakow' or 'in Zakopane'."""
    if re.search(r"\bzakopan[ea-z]*\b", text, re.IGNORECASE):
        return "Zakopane"
    if re.search(r"\bkrak[oó]w[a-z]*\b", text, re.IGNORECASE):
        return "Krakow"
    if re.search(r"\bwarszaw[a-z]*\b", text, re.IGNORECASE):
        return "Warsaw"

    m = re.search(
        r"\b(?:to|in|at|do|w|na)\s+([A-ZŁŚĆŻŹÓĘĄ][A-Za-złśćżźóęąŁŚĆŻŹÓĘĄ\-]+(?:\s+[A-ZŁŚĆŻŹÓĘĄ][A-Za-złśćżźóęąŁŚĆŻŹÓĘĄ\-]+)?)",
        text,
    )
    if m:
        candidate = m.group(1).strip()
        words = candidate.split()
        clean_words = [
            w
            for w in words
            if w.lower() not in MONTH_MAP
            and w.lower()
            not in (
                "harness",
                "monday",
                "tuesday",
                "wednesday",
                "thursday",
                "friday",
                "saturday",
                "sunday",
                "trip",
                "wyjazd",
                "outing",
            )
        ]
        if clean_words:
            return " ".join(clean_words)
    return ""


def _parse_outing_offline(message: str, ref_dt: date) -> Optional[Dict[str, Any]]:
    """Deterministic parser for natural outing / trip / break announcements."""
    low = (message or "").lower()
    has_outing_word = any(k in low for k in OUTING_KEYWORDS)

    start_dt: Optional[date] = None
    end_dt: Optional[date] = None

    # Pattern 1: ISO range 2026-12-23 to/- 2026-12-27
    iso_matches = re.findall(r"\b(\d{4}-\d{2}-\d{2})\b", message)
    if len(iso_matches) >= 2:
        try:
            start_dt = datetime.strptime(iso_matches[0], "%Y-%m-%d").date()
            end_dt = datetime.strptime(iso_matches[1], "%Y-%m-%d").date()
        except ValueError:
            pass
    elif len(iso_matches) == 1 and has_outing_word:
        try:
            start_dt = datetime.strptime(iso_matches[0], "%Y-%m-%d").date()
            end_dt = start_dt
        except ValueError:
            pass

    # Pattern 2: "December 23-27" / "Dec 23 to 27" / "Dec 23 - Jan 2"
    if start_dt is None:
        month_names = "|".join(sorted(MONTH_MAP.keys(), key=len, reverse=True))
        m_cross = re.search(
            rf"\b({month_names})\.?\s+(\d{{1,2}})\s*(?:-|–|—|to|through|until|do)\s*({month_names})\.?\s+(\d{{1,2}})\b",
            low,
        )
        if m_cross:
            m1, d1 = MONTH_MAP[m_cross.group(1)], int(m_cross.group(2))
            m2, d2 = MONTH_MAP[m_cross.group(3)], int(m_cross.group(4))
            y1 = _resolve_year(m1, d1, ref_dt)
            y2 = y1 + 1 if m2 < m1 else y1
            try:
                start_dt = date(y1, m1, d1)
                end_dt = date(y2, m2, d2)
            except ValueError:
                pass

    if start_dt is None:
        month_names = "|".join(sorted(MONTH_MAP.keys(), key=len, reverse=True))
        m_same = re.search(
            rf"\b({month_names})\.?\s+(\d{{1,2}})\s*(?:-|–|—|to|through|until|do)\s*(\d{{1,2}})\b",
            low,
        )
        if m_same:
            m1 = MONTH_MAP[m_same.group(1)]
            d1, d2 = int(m_same.group(2)), int(m_same.group(3))
            y1 = _resolve_year(m1, d1, ref_dt)
            try:
                start_dt = date(y1, m1, d1)
                end_dt = date(y1, m1, d2)
            except ValueError:
                pass

    # Pattern 3: "23-27 December" or "23.12 - 27.12"
    if start_dt is None:
        m_dots = re.search(r"\b(\d{1,2})\.(\d{1,2})\s*(?:-|–|—|to|do)\s*(\d{1,2})\.(\d{1,2})\b", low)
        if m_dots:
            d1, m1 = int(m_dots.group(1)), int(m_dots.group(2))
            d2, m2 = int(m_dots.group(3)), int(m_dots.group(4))
            if 1 <= m1 <= 12 and 1 <= m2 <= 12:
                y1 = _resolve_year(m1, d1, ref_dt)
                y2 = y1 + 1 if m2 < m1 else y1
                try:
                    start_dt = date(y1, m1, d1)
                    end_dt = date(y2, m2, d2)
                except ValueError:
                    pass

    # Pattern 4: single month+day with outing keyword ("trip on Dec 24")
    if start_dt is None and has_outing_word:
        month_names = "|".join(sorted(MONTH_MAP.keys(), key=len, reverse=True))
        m_single = re.search(rf"\b({month_names})\.?\s+(\d{{1,2}})\b", low)
        if m_single:
            m1, d1 = MONTH_MAP[m_single.group(1)], int(m_single.group(2))
            y1 = _resolve_year(m1, d1, ref_dt)
            try:
                start_dt = date(y1, m1, d1)
                end_dt = start_dt
            except ValueError:
                pass
        elif "tomorrow" in low:
            start_dt = ref_dt + timedelta(days=1)
            end_dt = start_dt
        elif "this weekend" in low:
            days_to_sat = (5 - ref_dt.weekday()) % 7
            start_dt = ref_dt + timedelta(days=days_to_sat)
            end_dt = start_dt + timedelta(days=1)

    if start_dt is None or end_dt is None:
        if "zakopane" in low:
            # Zakopane fast-preset when exact dates are not yet provided in prompt
            days_to_fri = (4 - ref_dt.weekday()) % 7 or 7
            start_dt = ref_dt + timedelta(days=days_to_fri)
            end_dt = start_dt + timedelta(days=3)
            return {
                "name": "Zakopane Expedition (Dates TBD)",
                "destination": "Zakopane",
                "start_date": start_dt.strftime("%Y-%m-%d"),
                "end_date": end_dt.strftime("%Y-%m-%d"),
                "mode": "travel",
                "description": "Family trip to Zakopane. Edit exact dates on-screen below, check exam conflicts, and confirm schedule diff.",
            }
        return None
    if end_dt < start_dt:
        start_dt, end_dt = end_dt, start_dt
    if not has_outing_word and (end_dt - start_dt).days == 0:
        return None

    is_break = any(k in low for k in BREAK_KEYWORDS) and not any(
        w in low for w in ("trip", "flight", "travel", "wyjazd", "outing")
    )
    mode = "break" if is_break else "travel"
    destination = _extract_destination(message) or ("At-Home Break Sprint" if mode == "break" else "Outing / Trip")
    span_label = f"{start_dt.strftime('%b %d')} – {end_dt.strftime('%b %d')}" if start_dt != end_dt else start_dt.strftime("%b %d")
    name = (
        f"Break Sprint ({span_label})"
        if mode == "break"
        else (f"{destination} Trip" if destination != "Outing / Trip" else f"Trip ({span_label})")
    )
    desc = (
        "No-school break sprint: morning programming, JetBrains/CS & Sidequests; zero school pressure."
        if mode == "break"
        else f"Confirmed outing ({span_label}). School deadlines paused; 30-45m low-friction maintenance floor."
    )
    return {
        "name": name,
        "destination": destination,
        "start_date": start_dt.strftime("%Y-%m-%d"),
        "end_date": end_dt.strftime("%Y-%m-%d"),
        "mode": mode,
        "description": desc,
    }


def _load_schedule_summary_by_weekday() -> Dict[str, str]:
    defaults = {
        "Monday": "School + 60m Study + Boxing",
        "Tuesday": "School + 90m Study + Gym",
        "Wednesday": "School + 60m Study + Boxing",
        "Thursday": "School + 90m Study + Gym",
        "Friday": "School + 90m JetBrains/Wrap-up",
        "Saturday": "Optional 5k + 90m Catch-Up",
        "Sunday": "Full Rest + Weekly Prep",
    }
    if SCHEDULES_FILE.exists():
        try:
            data = json.loads(SCHEDULES_FILE.read_text(encoding="utf-8"))
            for sched in (data.get("schedules") or {}).values():
                for day_name in sched.get("days", []):
                    name = sched.get("name", "")
                    if ":" in name:
                        name = name.split(":", 1)[1].strip()
                    defaults[day_name] = name or defaults.get(day_name, "Standard Day")
        except Exception:
            pass
    return defaults


def _compute_conflicts_and_diff(
    start_str: str,
    end_str: str,
    mode: str,
    destination: str,
    conn: sqlite3.Connection,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Queries overlapping exams/homework and builds a day-by-day Before -> After rearrangement diff."""
    try:
        s_dt = datetime.strptime(start_str[:10], "%Y-%m-%d").date()
        e_dt = datetime.strptime(end_str[:10], "%Y-%m-%d").date()
    except Exception:
        return [], []
    if e_dt < s_dt:
        s_dt, e_dt = e_dt, s_dt

    cursor = conn.cursor()
    affected_exams: List[Dict[str, Any]] = []
    try:
        cursor.execute(
            """
            SELECT id, subject, title, exam_date, scope
            FROM school_exams
            WHERE completed = 0
              AND substr(trim(exam_date), 1, 10) >= ?
              AND substr(trim(exam_date), 1, 10) <= ?
            ORDER BY substr(trim(exam_date), 1, 10) ASC
            """,
            (s_dt.strftime("%Y-%m-%d"), e_dt.strftime("%Y-%m-%d")),
        )
        for r in cursor.fetchall():
            affected_exams.append({
                "id": r["id"],
                "subject": r["subject"],
                "title": r["title"],
                "exam_date": str(r["exam_date"] or "")[:10],
                "scope": r["scope"] or "",
            })
    except Exception:
        pass

    weekday_map = _load_schedule_summary_by_weekday()
    diff_days: List[Dict[str, Any]] = []
    total_days = min(31, (e_dt - s_dt).days + 1)
    for offset in range(total_days):
        cur = s_dt + timedelta(days=offset)
        wname = cur.strftime("%A")
        before_label = weekday_map.get(wname, "Standard Routine")
        if mode == "break":
            training_keep = " + Boxing" if wname in ("Monday", "Wednesday") else (" + Gym" if wname in ("Tuesday", "Thursday") else "")
            after_label = f"Break Sprint: 2.5h Morning Coding & Sidequests{training_keep}"
            badge = "BREAK SPRINT"
        else:
            after_label = f"Travel Floor ({destination or 'Away'}): 30-45m Anchor • School Paused"
            badge = "TRAVEL"
        diff_days.append({
            "date": cur.strftime("%Y-%m-%d"),
            "weekday": wname,
            "before": before_label,
            "after": after_label,
            "badge": badge,
        })

    return affected_exams, diff_days


def build_outing_a2ui_envelope(
    outing: Dict[str, Any],
    affected_exams: List[Dict[str, Any]],
    schedule_diff: List[Dict[str, Any]],
    provider: str,
    reply: str,
) -> Dict[str, Any]:
    """Constructs a strict A2UI v1.0 `agent_to_renderer` envelope using Harness's approved catalog."""
    start_str = outing["start_date"]
    end_str = outing["end_date"]
    mode = outing.get("mode", "travel")
    surface_id = f"outing_{start_str.replace('-', '')}_{end_str.replace('-', '')}"

    components: List[Dict[str, Any]] = [
        {
            "id": "outing_heading",
            "@catalogId": "Heading",
            "eyebrow": f"A2UI PLANNER • {provider.upper()}",
            "title": outing.get("name") or f"Outing ({start_str} -> {end_str})",
            "badge": "BREAK SPRINT" if mode == "break" else "TRAVEL PROPOSAL",
            "badgeTone": "lavender" if mode == "break" else "optimal",
        },
        {
            "id": "outing_summary",
            "@catalogId": "OutingSummaryCard",
            "namePath": "@path:/outing/name",
            "destinationPath": "@path:/outing/destination",
            "descriptionPath": "@path:/outing/description",
        },
        {
            "id": "outing_dates",
            "@catalogId": "DateRangeField",
            "label": "Confirmed Dates (Editable)",
            "startPath": "@path:/outing/start_date",
            "endPath": "@path:/outing/end_date",
        },
        {
            "id": "outing_mode",
            "@catalogId": "ModeSelector",
            "label": "Day Protocol During Window",
            "valuePath": "@path:/outing/mode",
            "options": [
                {"value": "travel", "label": "Travel (30-45m Maintenance)"},
                {"value": "break", "label": "Break Sprint (Programming & Sidequests)"},
            ],
        },
    ]

    if affected_exams:
        components.append({
            "id": "outing_conflicts",
            "@catalogId": "ConflictAlert",
            "severity": "warn",
            "title": f"{len(affected_exams)} Scheduled Test(s) Overlap This Window",
            "itemsPath": "@path:/affected_exams",
        })

    components.append({
        "id": "outing_diff",
        "@catalogId": "ScheduleDiff",
        "title": f"Rearranged Plan ({len(schedule_diff)} Day{'s' if len(schedule_diff) != 1 else ''})",
        "daysPath": "@path:/schedule_diff",
    })

    components.append({
        "id": "outing_actions",
        "@catalogId": "ActionBar",
        "actions": [
            {"label": "Apply to Harness", "style": "primary", "@call": "apply_outing"},
            {"label": "Dismiss", "style": "ghost", "@call": "cancel_surface"},
        ],
    })

    return {
        "surfaceId": surface_id,
        "provider": provider,
        "reply": reply,
        "messages": [
            {"createSurface": {"title": outing.get("name") or "Outing Proposal"}},
            {
                "updateDataModel": {
                    "data": {
                        "outing": outing,
                        "affected_exams": affected_exams,
                        "schedule_diff": schedule_diff,
                    }
                }
            },
            {"updateComponents": {"components": components}},
        ],
    }


